#!/usr/bin/env bash
# Smoke test: Jabber/XMPP with a local Prosody server (issue #135).
#
# Start a Prosody container, give the app a throwaway profile with one Jabber
# account, and prove both message directions against a scripted peer:
#   1. the peer sends a token, and the app writes it to its chat log,
#   2. the app sends a token, and the peer receives it.
#
# Run from anywhere:  scripts/smoke/jabber.sh
# Keep the work directory for inspection:  SMOKE_KEEP=1 scripts/smoke/jabber.sh
#
# Requirements: Docker running, uv, and the Automation permission for AdiumY on
# this terminal. See scripts/smoke/README.md.

set -euo pipefail

# The library sits beside this script, not relative to the caller.
# shellcheck source-path=SCRIPTDIR
source "$(dirname "${BASH_SOURCE[0]}")/lib/smoke.sh"

readonly CONTAINER="adiumy-smoke-jabber"
readonly DOMAIN="localhost"
readonly ACCOUNT_UID="smoke-a@$DOMAIN"
readonly ACCOUNT_PASSWORD="smoke-a-pass"
readonly PEER_UID="smoke-b@$DOMAIN"
readonly PEER_PASSWORD="smoke-b-pass"

pick_free_port() {
  python3 -I -c 'import socket
s = socket.socket()
s.bind(("127.0.0.1", 0))
print(s.getsockname()[1])
s.close()'
}

stop_server() {
  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
}

write_server_config() {
  local path="$SMOKE_WORK/prosody.cfg.lua"
  cat >"$path" <<EOF
-- Generated by scripts/smoke/jabber.sh. A local test server only.
-- TLS is off and plaintext authentication is on, because the client under
-- test connects over loopback inside one machine.
allow_registration = false
c2s_require_encryption = false
allow_unencrypted_plain_auth = true
modules_disabled = { "tls", "s2s" }
modules_enabled = {
    "roster"; "saslauth"; "disco"; "ping"; "posix"; "limits";
    "carbons"; "mam"; "private"; "blocklist"; "offline";
}
archive_expires_after = "never"

VirtualHost "$DOMAIN"
    authentication = "internal_plain"

Component "conference.$DOMAIN" "muc"
    modules_enabled = { "ping" }
EOF
  printf '%s\n' "$path"
}

start_server() {
  local port="$1" config
  config="$(write_server_config)"

  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
  docker run -d --name "$CONTAINER" \
    -p "$port:5222" \
    -v "$config:/etc/prosody/prosody.cfg.lua:ro" \
    --user prosody \
    --entrypoint prosody \
    prosody/prosody -F >/dev/null ||
    smoke_fail "server start" "docker run failed" "check that Docker is running"

  smoke_step "prosody starting on port $port"
  smoke_wait_for 30 "prosody to accept connections" smoke_port_is_open "$port"
}

smoke_port_is_open() {
  local port="$1"
  python3 -I -c "
import socket, sys
s = socket.socket()
s.settimeout(1)
sys.exit(0 if s.connect_ex(('127.0.0.1', $port)) == 0 else 1)"
}

register_users() {
  local command
  for command in \
    "prosodyctl register smoke-a $DOMAIN $ACCOUNT_PASSWORD" \
    "prosodyctl register smoke-b $DOMAIN $PEER_PASSWORD"; do
    if ! docker exec -u prosody "$CONTAINER" sh -c "$command" >/dev/null 2>&1; then
      smoke_fail "user registration" "prosodyctl failed: $command" \
        "read the server log: docker logs $CONTAINER"
    fi
  done
}

account_is_online() {
  local status
  status="$(osascript -e "tell application \"$APP_NAME\" to tell account \"$ACCOUNT_UID\" to get status type" 2>/dev/null || true)"
  [ "$status" = "available" ]
}

main() {
  smoke_require docker uv python3 osascript security
  smoke_begin jabber

  local port
  port="$(pick_free_port)"
  smoke_set_server_stop stop_server

  smoke_check_automation
  start_server "$port"
  register_users

  smoke_profile jabber "$ACCOUNT_UID" \
    "Connect Host=127.0.0.1" \
    "Connect Port=$port" \
    "Jabber:Require TLS=false" \
    "Jabber:Allow Plaintext Authentication=true" \
    "Jabber:Verify Certificates=false"
  smoke_keychain_add "$ACCOUNT_PASSWORD"

  smoke_launch_app
  smoke_go_online "$ACCOUNT_UID"
  smoke_wait_for "$SMOKE_CONNECT_TIMEOUT" "the account to come online" account_is_online
  smoke_step "account is online"

  local token
  token="smoke-$$-$(date +%s)"
  local incoming="FROM-PEER-$token" outgoing="FROM-ADIUM-$token"

  uv run --quiet --no-project --with slixmpp python3 -I "$SMOKE_DIR/peers/xmpp_peer.py" \
    --jid "$PEER_UID" --password "$PEER_PASSWORD" \
    --server 127.0.0.1 --port "$port" \
    --peer "$ACCOUNT_UID" \
    --send "$incoming" --expect "$outgoing" \
    --timeout "$SMOKE_MESSAGE_TIMEOUT" >"$SMOKE_WORK/logs/peer.out" 2>"$SMOKE_WORK/logs/peer.err" &
  local peer_pid=$!

  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the app to log the incoming message" \
    smoke_log_contains "$incoming"
  smoke_step "the app received the peer's message"

  smoke_send "$ACCOUNT_UID" "$PEER_UID" "$outgoing"

  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the peer to receive the app's message" \
    smoke_process_finished "$peer_pid"

  smoke_step "PASS: Jabber smoke test"
}

# True once the background peer exits with status 0.
smoke_process_finished() {
  local pid="$1"
  kill -0 "$pid" 2>/dev/null && return 1
  wait "$pid"
}

main "$@"
