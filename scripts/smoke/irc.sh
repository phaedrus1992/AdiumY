#!/usr/bin/env bash
# Smoke test: IRC with a local Ergo server (issue #134).
#
# Start an Ergo container, give the app a throwaway profile with one IRC
# account, and prove the transport:
#   1. the peer sends a private message, and the app writes it to its chat log,
#   2. the app sends a private message, and the peer receives it,
#   3. the app joins a channel, and the peer sees its nickname in that channel.
#
# Run from anywhere:  scripts/smoke/irc.sh
# Keep the work directory for inspection:  SMOKE_KEEP=1 scripts/smoke/irc.sh
#
# Requirements: Docker running, uv, and the Automation permission for AdiumY on
# this terminal. See scripts/smoke/README.md.

set -euo pipefail

# The library sits beside this script, not relative to the caller.
# shellcheck source-path=SCRIPTDIR
source "$(dirname "${BASH_SOURCE[0]}")/lib/smoke.sh"

readonly CONTAINER="adiumy-smoke-irc"
readonly IMAGE="ghcr.io/ergochat/ergo:stable"
readonly ACCOUNT_NICK="smoke-a"
readonly PEER_NICK="smoke-b"

pick_free_port() {
  python3 -I -c 'import socket
s = socket.socket()
s.bind(("127.0.0.1", 0))
print(s.getsockname()[1])
s.close()'
}

stop_server() {
  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
}

write_server_config() {
  local path="$SMOKE_WORK/ircd.yaml"
  cat >"$path" <<EOF
# Generated by scripts/smoke/irc.sh. A local test server only.
# Accounts and SASL are off, so a client connects with a nickname alone.
network:
    name: AdiumYSmoke

server:
    name: smoke.test
    listeners:
        ":6667": {}
    max-sendq: 96k
    check-ident: false

accounts:
    authentication-enabled: false
    registration:
        enabled: false
    require-sasl:
        enabled: false

datastore:
    path: /ircd/ircd.db
    autoupgrade: true

# Ergo refuses to start when a limit sits below its minimum, so the values come
# from the image's own default configuration.
limits:
    nicklen: 32
    identlen: 20
    realnamelen: 150
    channellen: 64
    awaylen: 390
    kicklen: 390
    topiclen: 390
    monitor-entries: 100
    whowas-entries: 100
    chan-list-modes: 100
    registration-messages: 1024
    multiline:
        max-bytes: 4096
        max-lines: 100

languages:
    enabled: false

logging:
    - method: stderr
      type: "* -userinput -useroutput"
      level: info
EOF
  printf '%s\n' "$path"
}

start_server() {
  local port="$1" config
  config="$(write_server_config)"

  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
  docker run -d --name "$CONTAINER" \
    -p "$port:6667" \
    -v "$config:/ircd/ircd.yaml:ro" \
    "$IMAGE" >/dev/null ||
    smoke_fail "server start" "docker run failed" "check that Docker is running"

  smoke_step "ergo starting on port $port"
  smoke_wait_for 30 "ergo to accept connections" smoke_port_is_open "$port"
}

smoke_port_is_open() {
  local port="$1"
  python3 -I -c "
import socket, sys
s = socket.socket()
s.settimeout(1)
sys.exit(0 if s.connect_ex(('127.0.0.1', $port)) == 0 else 1)"
}

account_is_online() {
  local status
  status="$(osascript -e "tell application \"$APP_NAME\" to tell account \"$ACCOUNT_NICK\" to get status type" 2>/dev/null || true)"
  [ "$status" = "available" ]
}

# Start the peer in the background. It sends one message and waits for the
# reply, so its exit status proves both directions.
#   start_peer <port> <message> <expected> [extra arguments...]
start_peer() {
  local port="$1" message="$2" expected="$3"
  shift 3
  python3 -I "$SMOKE_DIR/peers/irc_peer.py" \
    --server 127.0.0.1 --port "$port" --nick "$PEER_NICK" \
    --send "$message" --expect "$expected" \
    --timeout "$SMOKE_MESSAGE_TIMEOUT" "$@" \
    >"$SMOKE_WORK/logs/peer.out" 2>"$SMOKE_WORK/logs/peer.err" &
  SMOKE_PEER_PID=$!
}

smoke_process_finished() {
  kill -0 "$1" 2>/dev/null && return 1
  wait "$1"
}

main() {
  smoke_require docker python3 osascript
  smoke_begin irc

  local port
  port="$(pick_free_port)"
  smoke_set_server_stop stop_server

  smoke_check_automation
  start_server "$port"

  smoke_profile irc "$ACCOUNT_NICK" \
    "Connect Host=127.0.0.1" \
    "Connect Port=$port" \
    "IRC:Use SSL=false" \
    "IRC:Realname=$ACCOUNT_NICK"

  smoke_launch_app
  smoke_go_online "$ACCOUNT_NICK"
  smoke_wait_for "$SMOKE_CONNECT_TIMEOUT" "the account to come online" account_is_online
  smoke_step "account is online"

  local token
  token="smoke-$$-$(date +%s)"
  local incoming="FROM-PEER-$token" outgoing="FROM-ADIUM-$token"

  start_peer "$port" "$incoming" "$outgoing" --send-to "$ACCOUNT_NICK"

  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the app to log the incoming message" \
    smoke_log_contains "$incoming"
  smoke_step "the app received the peer's private message"

  smoke_send "$ACCOUNT_NICK" "$PEER_NICK" "$outgoing"
  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the peer to receive the app's message" \
    smoke_process_finished "$SMOKE_PEER_PID"
  smoke_step "the peer received the app's private message"

  smoke_channel_check "$port" "$token"
  smoke_step "PASS: IRC smoke test"
}

# The app joins a channel through its own URL handler, then the peer joins the
# same channel and looks for the app's nickname in it.
smoke_channel_check() {
  local port="$1" token="$2"
  local channel="#smoke-$token"
  local marker="CHANNEL-$token"

  open "irc://127.0.0.1:$port/$channel"
  smoke_step "asked the app to join $channel"

  start_peer "$port" "$marker" "$marker" \
    --send-to "$channel" --join "$channel" --require-nick "$ACCOUNT_NICK"
  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the peer to see the app in $channel" \
    smoke_process_finished "$SMOKE_PEER_PID"
  smoke_step "the peer saw the app in $channel"
}

main "$@"
