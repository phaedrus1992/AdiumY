#!/usr/bin/env bash
# Smoke test: IRC with a local Ergo server (issue #134).
#
# Start an Ergo container, give the app a throwaway profile with one IRC
# account, and prove the transport:
#   1. the peer sends a private message, and the app writes it to its chat log,
#   2. the app sends a private message, and the peer receives it,
#   3. the app joins a channel, the peer sees its nickname in that channel, and
#      a message written to the channel reaches the app.
#
# Run from anywhere:  scripts/smoke/irc.sh
# Keep the work directory for inspection:  SMOKE_KEEP=1 scripts/smoke/irc.sh
#
# Requirements: Docker running, and the Automation permission for AdiumY on
# this terminal. See scripts/smoke/README.md.

set -euo pipefail

# The library sits beside this script, not relative to the caller.
# shellcheck source-path=SCRIPTDIR
source "$(dirname "${BASH_SOURCE[0]}")/lib/smoke.sh"

readonly CONTAINER="adiumy-smoke-irc"
# Pinned by digest: a moving tag would change the server under the test.
readonly IMAGE="ghcr.io/ergochat/ergo@sha256:72db5b93b437ea0512fb79d9d4d035f0916ccba07ed736dec19e8d5b5a73f972"
readonly ACCOUNT_NICK="smoke-a"
readonly PEER_NICK="smoke-b"

print_server_log() {
  docker logs "$CONTAINER" 2>&1
}

stop_server() {
  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
}

write_server_config() {
  local path="$SMOKE_WORK/ircd.yaml"
  cat >"$path" <<'EOF'
# Generated by scripts/smoke/irc.sh. A local test server only.
# Accounts and SASL are off, so a client connects with a nickname alone.
network:
    name: AdiumYSmoke

server:
    name: smoke.test
    listeners:
        ":6667": {}
    max-sendq: 96k
    check-ident: false

accounts:
    authentication-enabled: false
    registration:
        enabled: false
    require-sasl:
        enabled: false

datastore:
    path: /ircd/ircd.db
    autoupgrade: true

# Ergo refuses to start when a limit sits below its minimum, so the values come
# from the image's own default configuration.
limits:
    nicklen: 32
    identlen: 20
    realnamelen: 150
    channellen: 64
    awaylen: 390
    kicklen: 390
    topiclen: 390
    monitor-entries: 100
    whowas-entries: 100
    chan-list-modes: 100
    registration-messages: 1024
    multiline:
        max-bytes: 4096
        max-lines: 100

languages:
    enabled: false

logging:
    - method: stderr
      type: "* -userinput -useroutput"
      level: info
EOF
  printf '%s\n' "$path"
}

start_server() {
  local port="$1" config output status=0
  config="$(write_server_config)"

  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
  output="$(docker run -d --name "$CONTAINER" \
    -p "$port:6667" \
    -v "$config:/ircd/ircd.yaml:ro" \
    "$IMAGE" 2>&1)" || status=$?
  [ "$status" -eq 0 ] ||
    smoke_fail "server start" "docker run exited $status: $output" \
      "check that Docker is running and that no container holds the name $CONTAINER"

  smoke_step "ergo starting on port $port"
  smoke_wait_for_server "$port"
}

# Start the peer in the background for one step of the test.
#   start_peer <stage> <port> [peer arguments...]
start_peer() {
  local stage="$1" port="$2"
  shift 2

  python3 -I "$SMOKE_DIR/peers/irc_peer.py" \
    --server 127.0.0.1 --port "$port" --nick "$PEER_NICK" \
    --timeout "$SMOKE_MESSAGE_TIMEOUT" "$@" \
    >"$SMOKE_WORK/logs/peer-$stage.out" 2>"$SMOKE_WORK/logs/peer-$stage.err" &
  SMOKE_PEER_PID=$!
  SMOKE_PEER_STATUS=""
}

main() {
  smoke_require docker python3 osascript
  smoke_begin irc

  local port
  port="$(smoke_pick_free_port)"
  smoke_set_server_stop stop_server
  smoke_set_server_log print_server_log

  start_server "$port"

  smoke_profile irc "$ACCOUNT_NICK" \
    "Connect Host=127.0.0.1" \
    "Connect Port=$port" \
    "IRC:Use SSL=false" \
    "IRC:Realname=$ACCOUNT_NICK"

  smoke_launch_app
  smoke_go_online "$ACCOUNT_NICK"
  # The account's status says nothing about its connection, so wait for the
  # session the server records.
  smoke_wait_for "$SMOKE_CONNECT_TIMEOUT" "the app's session on the server" \
    smoke_server_log_has "Client connected \[$ACCOUNT_NICK\]"
  smoke_step "the app is connected"

  local token
  token="smoke-$$-$(date +%s)"
  local incoming="FROM-PEER-$token" outgoing="FROM-ADIUM-$token"

  start_peer message "$port" --send "$incoming" --send-to "$ACCOUNT_NICK" \
    --expect "$outgoing"

  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the app to log the incoming message" \
    smoke_log_contains "$incoming"
  smoke_step "the app received the peer's private message"

  smoke_send "$ACCOUNT_NICK" "$PEER_NICK" "$outgoing"
  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the peer to receive the app's message" \
    smoke_peer_succeeded "$SMOKE_PEER_PID" "$SMOKE_WORK/logs/peer-message.err"
  smoke_step "the peer received the app's private message"

  smoke_channel_check "$port" "$token"
  smoke_step "PASS: IRC smoke test"
}

# The app joins a channel through its own URL handler. The peer then joins the
# same channel, waits until the app's nickname is in it, and writes to the
# channel, which the app must log.
smoke_channel_check() {
  local port="$1" token="$2"
  local channel="#smoke-$token"
  local marker="CHANNEL-$token"
  local url="irc://127.0.0.1:$port/$channel"

  open "$url" || smoke_fail "channel join" "open $url failed" \
    "check that the app registers the irc URL scheme"
  smoke_step "asked the app to join $channel"

  start_peer channel "$port" --join "$channel" --require-nick "$ACCOUNT_NICK" \
    --send "$marker" --send-to "$channel"

  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the peer to see the app in $channel" \
    smoke_peer_succeeded "$SMOKE_PEER_PID" "$SMOKE_WORK/logs/peer-channel.err"
  smoke_step "the peer saw the app in $channel"

  smoke_wait_for "$SMOKE_MESSAGE_TIMEOUT" "the app to log the channel message" \
    smoke_log_contains "$marker"
  smoke_step "the app received the channel message"
}

main "$@"
